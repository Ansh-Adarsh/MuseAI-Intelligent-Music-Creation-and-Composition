/**
 * HTTP implementations against the PROPOSED MuseAI FastAPI endpoints:
 *   POST /api/music/generate     -> TaskAccepted
 *   POST /api/music/analyze      -> AudioAnalysisResponse (or TaskAccepted)
 *   POST /api/music/edit         -> TaskAccepted
 *   GET  /api/music/status/{id}  -> TaskStatus
 *   GET  /api/music/result/{id}  -> MusicGenerationResponse | MusicEditResponse
 * These are not ACE-Step endpoints; the backend wraps ACE-Step behind them.
 */
import { endpoints } from '@/config/env';
import type { AudioAnalysisService, MusicEditingService, MusicGenerationService } from '../types';
import type {
  AudioAnalysisResponse,
  MusicEditResponse,
  MusicGenerationResponse,
  TaskAccepted,
} from '@/types/music';
import { absoluteUrl, apiRequest, awaitTaskResult, uploadWithProgress } from './apiClient';

function isTask(x: unknown): x is TaskAccepted {
  return !!x && typeof x === 'object' && 'taskId' in x && 'state' in x && !('global' in x);
}

export const httpGenerationService: MusicGenerationService = {
  async generateMusic(request, opts) {
    const accepted = await apiRequest<TaskAccepted>(endpoints.generate, {
      method: 'POST', body: JSON.stringify(request), signal: opts?.signal,
    });
    const res = await awaitTaskResult<MusicGenerationResponse>(accepted, opts);
    return { ...res, takes: res.takes.map((t) => ({ ...t, url: absoluteUrl(t.url) })), isMock: false };
  },
};

export const httpEditingService: MusicEditingService = {
  async editMusic(request, opts) {
    const accepted = await apiRequest<TaskAccepted>(endpoints.edit, {
      method: 'POST', body: JSON.stringify(request), signal: opts?.signal,
    });
    const res = await awaitTaskResult<MusicEditResponse>(accepted, opts);
    return { ...res, editedAudio: { ...res.editedAudio, url: absoluteUrl(res.editedAudio.url) }, isMock: false };
  },
};

export const httpAnalysisService: AudioAnalysisService = {
  async analyzeAudio(audio, opts) {
    let res: AudioAnalysisResponse | TaskAccepted;
    if (audio.backendFileId) {
      // Already on the backend (e.g. generated by MuseAI): analyze by reference, no re-upload.
      res = await apiRequest(endpoints.analyze, {
        method: 'POST', body: JSON.stringify({ audioFileId: audio.backendFileId }), signal: opts?.signal,
      });
    } else {
      const form = new FormData();
      form.append('file', audio.blob, audio.name);
      res = await uploadWithProgress(endpoints.analyze, form, (p) =>
        opts?.onStatus?.({ taskId: 'upload', state: 'running', progress: p, message: `Uploading ${Math.round(p * 100)}%` }), opts?.signal);
    }
    if (isTask(res)) return { ...(await awaitTaskResult<AudioAnalysisResponse>(res, opts)), isMock: false };
    return { ...res, isMock: false };
  },
};
